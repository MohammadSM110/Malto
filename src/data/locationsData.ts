export const IRANIAN_CITIES: string[] = IRAN_CITIES_DATA.map((c) => c.cityName);

export const DEFAULT_CITY = 'تهران';
export const DEFAULT_DISTRICT = 'شهرک غرب';

/**
 * Returns neighborhoods for a given city name. Defaults to Tehran districts if city not found.
 */
export function getDistrictsForCity(cityName?: string): string[] {
  if (!cityName) {
    const tehran = IRAN_CITIES_DATA.find((c) => c.cityName === DEFAULT_CITY);
    return tehran ? tehran.districts : [];
  }
  const found = IRAN_CITIES_DATA.find(
    (c) => c.cityName === cityName || c.id === cityName.toLowerCase()
  );
  if (found) {
    return found.districts;
  }
  // Fallback to Tehran if city not found
  const tehran = IRAN_CITIES_DATA.find((c) => c.cityName === DEFAULT_CITY);
  return tehran ? tehran.districts : [];
}
